import { ref, watch } from 'vue'
import type { DuplicateResolutionAction } from '@/types/peso/provincialPeso/applicantEntry'
import { useApplicantNewEntry } from '@/composables/peso/provincialPeso/useApplicantNewEntry'

/**
 * Everything the New Applicant Entry page (ApplicantNewEntry.vue) and its steps (NewEntry/*.vue) use:
 * the NSRP form plus the "existing applicant found" resolution, wired together once.
 */
export function useApplicantNewEntryPage(options: Parameters<typeof useApplicantNewEntry>[0]) {
  const {
    isFormSubmitting,
    handleCancel,
    handleSubmit,
    duplicateMatch,
    isDuplicateModalOpen,
    handleDuplicateResolution,
    steps,
    currentStep,
    nextStep,
    prevStep,
    goToStep,

    // PSGC
    psgcProvinces,
    psgcCities,
    psgcBarangays,
    selectedRegion,
    selectedProvince,
    selectedCity,
    selectedBarangay,
    onProvinceChange,
    onCityChange,
    onBarangayChange,

    // Step 1
    firstName,
    middleName,
    surname,
    suffix,
    dateOfBirthFormatted,
    onDobInput,
    age,
    sex,
    civilStatus,
    religion,
    religionOptions,
    getCourseOptions,
    trainingOptions,
    eligibilityTitleOptions,
    isLoadingReferenceLists,
    formResetCount,
    todayMax,
    heightFt,
    tin,
    primaryContactNumber,
    additionalContactNumbers,
    newAdditionalContact,
    email,
    street,
    village,
    addContactNumber,
    removeContactNumber,

    // Step 2
    employmentStatus,
    employmentType,
    unemployedReason,
    monthsLookingForWork,
    selfEmployedType,
    is4psBeneficiary,
    householdId4ps,
    hasDisability,
    selectedDisabilities,
    disabilityOthers,
    isOfw,
    ofwCountry,
    isFormerOfw,
    formerOfwCountry,
    formerOfwReturnDate,
    toggleDisability,
    disabilityOptions,

    // Step 3
    currentlyInSchool,
    educationalBackground,
    addEducationRow,
    removeEducationRow,

    // Step 4
    workExperiences,
    addWorkRow,
    removeWorkRow,
    vocationalTrainings,
    addVocationalRow,
    removeVocationalRow,

    // Step 5
    eligibilities,
    addEligibilityRow,
    removeEligibilityRow,
    otherSkills,
    newSkillTag,
    otherSkillsSpecified,
    addSkillTag,
    removeSkillTag,
    toggleSkillOption,
    skillOptions,
    languageProficiencies,
    newLanguageName,
    addLanguage,
    removeLanguage,

    // Step 6
    preferredOccupations,
    newOccupationTag,
    addOccupation,
    removeOccupation,
    preferredLocalLocations,
    newLocalLocationTag,
    addLocalLocation,
    removeLocalLocation,
    preferredOverseasLocations,
    newOverseasLocationTag,
    addOverseasLocation,
    removeOverseasLocation,
    jobTypePreference,
    toggleJobType,
    jobTypeOptions,
    referredPrograms,
    toggleProgram,
    programOptions,
    documentsSubmitted,
    toggleDocument,
    documentOptions,
    assessedByName,
    assessmentDate,
    profileId,
  } = useApplicantNewEntry(options)

  const duplicateAction = ref<DuplicateResolutionAction>('link_program')
  const duplicateProgram = ref<string>('SPES')

  watch(
    () => duplicateMatch.value,
    (match) => {
      if (match) {
        duplicateAction.value = 'link_program'
        duplicateProgram.value = referredPrograms.value[0] || programOptions[0] || 'SPES'
      }
    }
  )

  const confirmDuplicateResolution = () => {
    if (!duplicateMatch.value) return
    handleDuplicateResolution({
      action: duplicateAction.value,
      targetProgram: duplicateProgram.value,
      existingApplicantId: duplicateMatch.value.existingApplicant.id,
    })
  }

  return {
    isFormSubmitting,
    handleCancel,
    handleSubmit,
    duplicateMatch,
    isDuplicateModalOpen,
    handleDuplicateResolution,
    steps,
    currentStep,
    nextStep,
    prevStep,
    goToStep,
    psgcProvinces,
    psgcCities,
    psgcBarangays,
    selectedRegion,
    selectedProvince,
    selectedCity,
    selectedBarangay,
    onProvinceChange,
    onCityChange,
    onBarangayChange,
    firstName,
    middleName,
    surname,
    suffix,
    dateOfBirthFormatted,
    onDobInput,
    age,
    sex,
    civilStatus,
    religion,
    religionOptions,
    getCourseOptions,
    trainingOptions,
    eligibilityTitleOptions,
    isLoadingReferenceLists,
    formResetCount,
    todayMax,
    heightFt,
    tin,
    primaryContactNumber,
    additionalContactNumbers,
    newAdditionalContact,
    email,
    street,
    village,
    addContactNumber,
    removeContactNumber,
    employmentStatus,
    employmentType,
    unemployedReason,
    monthsLookingForWork,
    selfEmployedType,
    is4psBeneficiary,
    householdId4ps,
    hasDisability,
    selectedDisabilities,
    disabilityOthers,
    isOfw,
    ofwCountry,
    isFormerOfw,
    formerOfwCountry,
    formerOfwReturnDate,
    toggleDisability,
    disabilityOptions,
    currentlyInSchool,
    educationalBackground,
    addEducationRow,
    removeEducationRow,
    workExperiences,
    addWorkRow,
    removeWorkRow,
    vocationalTrainings,
    addVocationalRow,
    removeVocationalRow,
    eligibilities,
    addEligibilityRow,
    removeEligibilityRow,
    otherSkills,
    newSkillTag,
    otherSkillsSpecified,
    addSkillTag,
    removeSkillTag,
    toggleSkillOption,
    skillOptions,
    languageProficiencies,
    newLanguageName,
    addLanguage,
    removeLanguage,
    preferredOccupations,
    newOccupationTag,
    addOccupation,
    removeOccupation,
    preferredLocalLocations,
    newLocalLocationTag,
    addLocalLocation,
    removeLocalLocation,
    preferredOverseasLocations,
    newOverseasLocationTag,
    addOverseasLocation,
    removeOverseasLocation,
    jobTypePreference,
    toggleJobType,
    jobTypeOptions,
    referredPrograms,
    toggleProgram,
    programOptions,
    documentsSubmitted,
    toggleDocument,
    documentOptions,
    assessedByName,
    assessmentDate,
    profileId,
    duplicateAction,
    duplicateProgram,
    confirmDuplicateResolution,
  }
}
