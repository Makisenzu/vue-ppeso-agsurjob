    applicantToEdit,
    isEditApplicantDialogOpen,
    isSavingApplicantReview,
    isEditingHiredApplicant,
    isRemarksRequired,
    isOrientationRequired,
    uploadedFileFor,
    isLoadingUploadedDocuments,
    editStatusOptions,
    editDocuments,
    editDocumentOptions,
