    applicants,
    applicantStatusData,
    applicantMaleLpiiData,
    applicantFemaleLpiiData,
    totalApplicantStatus,
    totalMaleApplicantLpii,
    totalFemaleApplicantLpii,
    filteredApplicants,
    paginatedApplicants,
    totalApplicantPages,
    availableMonths,
    selectedApplicantForDetails,
