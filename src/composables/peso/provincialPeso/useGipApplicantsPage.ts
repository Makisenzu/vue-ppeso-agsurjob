    openEditCandidateModal,
    saveEditedCandidate,
    confirmImport,
    resetBatchState,
    downloadTemplate,

    // Duplicate Review Dialog
    duplicateCandidate,
    isDuplicateModalOpen,
    openDuplicateModal,
    setAllDuplicatesAction,
    selectedDuplicateAction,
    selectedDuplicateProgram,
    duplicateActionOptions,
    duplicateProgramOptions,
