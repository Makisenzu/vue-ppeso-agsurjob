    clearSelection,
    donutTooltipTriggers,
    statusDonutTooltipTriggers,
    getInitials,
    getApplicantAvatar,
    formatDateDisplay,
    getApplicantDocuments,
    goBack,
    resetFilters,
    openApplicantDetails,
    closeApplicantDetails,
    openEditApplicantDialog,
    exportCsv,
    refreshApplicantsData,
    navigateToPriority,
    setFileInputRef,
    triggerFileInput,
    handleUploadBatchClick,
    applicantToRemove,
    isRemoveDialogOpen,
    isRemoving,
    promptRemoveApplicant,
    cancelRemoveApplicant,
    showApplicantCards,
    getApplicantSwipeActions,
    getApplicantCard,
    confirmRemoveApplicant,
    isBulkDeleteDialogOpen,
    isBulkDeleting,
    handleBulkDelete,
    isBulkDeployDialogOpen,
